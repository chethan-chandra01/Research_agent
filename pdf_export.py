from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable, Table, TableStyle, PageBreak
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_JUSTIFY
from datetime import datetime
import hashlib, re, io

def generate_doi(topic):
    h = hashlib.md5(topic.encode()).hexdigest()[:8].upper()
    return f"ResearchAI-{datetime.now().year}-{h}"

def markdown_to_pdf_bytes(report_text, topic):
    buffer = io.BytesIO()
    doi    = generate_doi(topic)
    now    = datetime.now().strftime("%B %d, %Y")

    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        rightMargin=2.5*cm, leftMargin=2.5*cm,
        topMargin=2.5*cm,   bottomMargin=2.5*cm,
        title=f"Research Report: {topic}",
        author="ResearchAI Agent"
    )

    NAVY  = colors.HexColor("#1e3a5f")
    BLUE  = colors.HexColor("#2563eb")
    GRAY  = colors.HexColor("#64748b")
    LGRAY = colors.HexColor("#f1f5f9")
    BLACK = colors.HexColor("#0f172a")
    WHITE = colors.white
    AMBER = colors.HexColor("#f59e0b")
    RED   = colors.HexColor("#ef4444")

    styles = getSampleStyleSheet()

    def style(name, **kwargs):
        return ParagraphStyle(name, parent=styles["Normal"], **kwargs)

    title_s    = style("T",  fontSize=24, textColor=WHITE,  alignment=TA_CENTER, fontName="Helvetica-Bold", leading=30, spaceAfter=6)
    subtitle_s = style("ST", fontSize=11, textColor=colors.HexColor("#94a3b8"), alignment=TA_CENTER, fontName="Helvetica", spaceAfter=4)
    doi_s      = style("DI", fontSize=9,  textColor=colors.HexColor("#60a5fa"), alignment=TA_CENTER, fontName="Helvetica")
    h1_s       = style("H1", fontSize=15, textColor=NAVY,   spaceBefore=16, spaceAfter=6,  fontName="Helvetica-Bold")
    h2_s       = style("H2", fontSize=12, textColor=BLUE,   spaceBefore=10, spaceAfter=4,  fontName="Helvetica-Bold")
    body_s     = style("B",  fontSize=10.5, textColor=BLACK, leading=17, spaceAfter=5, alignment=TA_JUSTIFY, fontName="Helvetica")
    bullet_s   = style("BU", fontSize=10.5, textColor=BLACK, leading=16, spaceAfter=3, leftIndent=16, fontName="Helvetica")
    ref_s      = style("R",  fontSize=9,  textColor=GRAY,   leading=13, spaceAfter=3, fontName="Helvetica")
    contra_s   = style("CO", fontSize=10, textColor=colors.HexColor("#92400e"),
                       backColor=colors.HexColor("#fef3c7"), leftIndent=12, rightIndent=12,
                       spaceBefore=6, spaceAfter=6, leading=16, fontName="Helvetica-Oblique",
                       borderColor=AMBER, borderWidth=1, borderPad=6)
    meta_s     = style("ME", fontSize=9,  textColor=colors.HexColor("#94a3b8"), alignment=TA_CENTER, fontName="Helvetica")

    story = []

    # Cover page
    cover_data = [[Paragraph("Research Report", title_s)]]
    cover_table = Table(cover_data, colWidths=[16*cm])
    cover_table.setStyle(TableStyle([
        ("BACKGROUND",    (0,0),(-1,-1), NAVY),
        ("TOPPADDING",    (0,0),(-1,-1), 28),
        ("BOTTOMPADDING", (0,0),(-1,-1), 28),
        ("LEFTPADDING",   (0,0),(-1,-1), 20),
        ("RIGHTPADDING",  (0,0),(-1,-1), 20),
    ]))
    story.append(Spacer(1, 2*cm))
    story.append(cover_table)
    story.append(Spacer(1, 0.5*cm))

    topic_data = [[Paragraph(topic, style("TP", fontSize=14, textColor=NAVY, alignment=TA_CENTER, fontName="Helvetica-Bold", leading=20))]]
    topic_table = Table(topic_data, colWidths=[16*cm])
    topic_table.setStyle(TableStyle([
        ("BACKGROUND",    (0,0),(-1,-1), LGRAY),
        ("TOPPADDING",    (0,0),(-1,-1), 14),
        ("BOTTOMPADDING", (0,0),(-1,-1), 14),
        ("LEFTPADDING",   (0,0),(-1,-1), 16),
        ("RIGHTPADDING",  (0,0),(-1,-1), 16),
        ("BOX",           (0,0),(-1,-1), 0.5, colors.HexColor("#cbd5e1")),
    ]))
    story.append(topic_table)
    story.append(Spacer(1, 0.4*cm))
    story.append(Paragraph(f"DOI: {doi}", doi_s))
    story.append(Spacer(1, 0.2*cm))
    story.append(Paragraph(f"Generated by ResearchAI Agent  ·  {now}", meta_s))
    story.append(Spacer(1, 0.2*cm))
    story.append(Paragraph("Sources: arXiv · Semantic Scholar · Open Library · Trusted Web · Gemini 2.5 Flash", meta_s))
    story.append(PageBreak())

    # Body
    in_refs = False
    lines   = report_text.split("\n")

    def add_footer_note(story):
        story.append(Spacer(1, 0.3*cm))
        story.append(HRFlowable(width="100%", thickness=0.3, color=colors.HexColor("#e2e8f0"), spaceAfter=4))
        story.append(Paragraph(f"ResearchAI Agent  ·  {topic[:60]}  ·  {doi}", meta_s))

    for line in lines:
        line_stripped = line.strip()
        if not line_stripped:
            story.append(Spacer(1, 0.18*cm))
            continue

        if line_stripped.startswith("## Full Reference List") or line_stripped.startswith("# Full Reference List"):
            story.append(PageBreak())
            story.append(Paragraph("Full Reference List", h1_s))
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#e2e8f0"), spaceAfter=6))
            in_refs = True
            continue

        if line_stripped.startswith("## References") or line_stripped.startswith("# References"):
            story.append(PageBreak())
            story.append(Paragraph("References", h1_s))
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#e2e8f0"), spaceAfter=6))
            in_refs = True
            continue

        if line_stripped.startswith("> CONTRADICTION NOTE"):
            text = line_stripped[1:].strip()
            story.append(Paragraph(f"⚠ {text}", contra_s))
            continue

        if line_stripped.startswith("### "):
            story.append(Paragraph(line_stripped[4:], h2_s))
            continue

        if line_stripped.startswith("## "):
            story.append(Spacer(1, 0.2*cm))
            story.append(Paragraph(line_stripped[3:], h1_s))
            story.append(HRFlowable(width="100%", thickness=0.4, color=colors.HexColor("#e2e8f0"), spaceAfter=4))
            continue

        if line_stripped.startswith("# "):
            story.append(Paragraph(line_stripped[2:], h1_s))
            story.append(HRFlowable(width="100%", thickness=1, color=BLUE, spaceAfter=6))
            continue

        if line_stripped == "---":
            story.append(HRFlowable(width="100%", thickness=0.4, color=colors.HexColor("#e2e8f0"), spaceAfter=4))
            continue

        if in_refs:
            safe = line_stripped.replace("&","&amp;").replace("<","&lt;").replace(">","&gt;")
            story.append(Paragraph(safe, ref_s))
            continue

        line_stripped = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", line_stripped)
        line_stripped = re.sub(r"\*(.+?)\*",     r"<i>\1</i>", line_stripped)
        line_stripped = re.sub(r"`(.+?)`",        r"<font name='Courier'>\1</font>", line_stripped)

        safe = (line_stripped
            .replace("&","&amp;")
            .replace("<b>","\x00B\x00").replace("</b>","\x01B\x01")
            .replace("<i>","\x00I\x00").replace("</i>","\x01I\x01")
            .replace("<font","\x00F\x00").replace("</font>","\x01F\x01"))
        safe = safe.replace("&","&amp;")
        safe = (safe
            .replace("\x00B\x00","<b>").replace("\x01B\x01","</b>")
            .replace("\x00I\x00","<i>").replace("\x01I\x01","</i>")
            .replace("\x00F\x00","<font").replace("\x01F\x01","</font>"))

        if line_stripped.startswith("- ") or line_stripped.startswith("• "):
            story.append(Paragraph("&bull;&nbsp;&nbsp;" + safe[2:], bullet_s))
        elif re.match(r"^\d+\.\s", line_stripped):
            story.append(Paragraph(safe, bullet_s))
        else:
            story.append(Paragraph(safe, body_s))

    add_footer_note(story)
    doc.build(story)
    buffer.seek(0)
    return buffer.read()